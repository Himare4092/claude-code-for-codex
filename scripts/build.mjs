import { build } from 'esbuild';
import { mkdir, writeFile, readFile, readdir, copyFile } from 'node:fs/promises';
import path from 'node:path';
const outdir='plugins/claude/dist';
await mkdir(outdir,{recursive:true});
const result=await build({entryPoints:['plugins/claude/src/server.mjs','plugins/claude/src/worker.mjs','plugins/claude/src/cli.mjs'],outdir,bundle:true,platform:'node',target:'node22',format:'esm',outExtension:{'.js':'.mjs'},banner:{js:'import { createRequire as __createRequire } from "node:module"; const require = __createRequire(import.meta.url);'},legalComments:'linked',logLevel:'info',metafile:true});
const roots=new Set();
for(const input of Object.keys(result.metafile.inputs)) {
  const index=input.lastIndexOf('node_modules/');if(index<0)continue;
  const parts=input.slice(index+13).split('/');
  roots.add(input.slice(0,index+13)+parts.slice(0,parts[0].startsWith('@')?2:1).join('/'));
}
const notices=[];
for(const root of [...roots].sort()) {
  const pkg=JSON.parse(await readFile(path.join(root,'package.json'),'utf8'));
  const files=(await readdir(root)).filter(name=>/^licen[sc]e(?:[.-]|$)/i.test(name));
  if(!files.length)throw new Error(`License file missing for bundled dependency: ${pkg.name}`);
  notices.push(`${pkg.name} ${pkg.version}\n${(await Promise.all(files.map(name=>readFile(path.join(root,name),'utf8')))).join('\n')}`);
}
await writeFile('plugins/claude/THIRD_PARTY_LICENSES.txt',notices.join('\n\n--------------------\n\n'));
await copyFile('LICENSE','plugins/claude/LICENSE');
for(const name of ['README.md','README.en.md','README.jp.md']) {
  const text=await readFile(name,'utf8');
  await writeFile(`plugins/claude/${name}`,text.replaceAll('(plugins/claude/THIRD_PARTY_LICENSES.txt)','(THIRD_PARTY_LICENSES.txt)'));
}
await writeFile(`${outdir}/README.txt`,'Generated by npm run build. Commit these bundles so installed plugins need only Node.js and Claude Code.\n');
